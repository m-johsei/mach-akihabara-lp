#!/usr/bin/env node
/*
 * fetch-instagram.js
 * Pulls the latest posts from the MACH Instagram account via the Instagram
 * Graph API and writes them into data/instagram-feed.json in the shape the
 * front-end expects.
 *
 * Runs in GitHub Actions (Node 20+, which has global fetch). The access token
 * lives ONLY in GitHub Secrets — never in the committed code or front-end JS.
 *
 * Required environment variables (set as GitHub repo Secrets):
 *   IG_USER_ID  - the Instagram Business/Creator account ID
 *   IG_TOKEN    - a long-lived access token (see INSTAGRAM-SETUP.md)
 * Optional:
 *   IG_LIMIT    - how many posts to fetch (default 9)
 *   IG_API_BASE - override API base (default https://graph.facebook.com/v21.0)
 *
 * Usage:  node scripts/fetch-instagram.js
 */
'use strict';
const fs = require('fs');
const path = require('path');

/*
 * Two supported auth modes (set IG_MODE):
 *   "instagram" (default) — Instagram API with Instagram Login.
 *        No Facebook Page / business portfolio involved.
 *        IG_TOKEN = Instagram long-lived token. IG_USER_ID optional ("me" is used).
 *        Endpoint: graph.instagram.com
 *   "facebook" — Instagram API with Facebook Login (Page token).
 *        IG_TOKEN = Page access token, IG_USER_ID = IG business account id (required).
 *        Endpoint: graph.facebook.com
 */
const MODE = (process.env.IG_MODE || 'instagram').toLowerCase();
const USER_ID = process.env.IG_USER_ID || 'me';
const TOKEN = process.env.IG_TOKEN;
const LIMIT = process.env.IG_LIMIT || '9';
const API_BASE = process.env.IG_API_BASE ||
  (MODE === 'facebook' ? 'https://graph.facebook.com/v21.0' : 'https://graph.instagram.com/v21.0');
const OUT = path.join(__dirname, '..', 'data', 'instagram-feed.json');
const FALLBACK = path.join(__dirname, '..', 'data', 'instagram-fallback.json');
const PROFILE = 'https://www.instagram.com/mach_tcg_akihabara/';

function fail(msg) {
  console.error('[instagram] ' + msg);
  // Keep the existing feed (or fall back) so the site never breaks on CI failure.
  if (!fs.existsSync(OUT) && fs.existsSync(FALLBACK)) {
    fs.copyFileSync(FALLBACK, OUT);
    console.error('[instagram] copied fallback -> instagram-feed.json');
  }
  process.exit(0); // exit 0 so a transient API hiccup doesn't fail the whole deploy
}

/* Instagram long-lived tokens last 60 days but can be refreshed indefinitely.
   Refreshing on every run keeps the token alive as long as the workflow runs
   at least once every 60 days. (Facebook Page tokens don't expire, so skip.) */
async function refreshToken() {
  if (MODE === 'facebook') return;
  try {
    const url = 'https://graph.instagram.com/refresh_access_token' +
      '?grant_type=ig_refresh_token&access_token=' + TOKEN;
    const res = await fetch(url);
    const j = await res.json();
    if (j.access_token) {
      console.log('[instagram] token refreshed, expires_in=' + j.expires_in + 's');
      // Expose the fresh token so the workflow can store it back into the secret.
      // ::add-mask:: keeps it redacted in the Actions log.
      if (process.env.GITHUB_OUTPUT) {
        console.log('::add-mask::' + j.access_token);
        fs.appendFileSync(process.env.GITHUB_OUTPUT, 'new_token=' + j.access_token + '\n');
      }
    } else {
      console.log('[instagram] token refresh skipped: ' + JSON.stringify(j.error || j));
    }
  } catch (e) {
    console.log('[instagram] token refresh failed (non-fatal): ' + e.message);
  }
}

async function main() {
  if (!TOKEN) return fail('Missing IG_TOKEN env var.');
  if (MODE === 'facebook' && (!process.env.IG_USER_ID)) {
    return fail('IG_USER_ID is required when IG_MODE=facebook.');
  }

  await refreshToken();

  const fields = 'id,caption,media_type,media_url,thumbnail_url,permalink,timestamp';
  const url = `${API_BASE}/${USER_ID}/media?fields=${fields}&limit=${LIMIT}&access_token=${TOKEN}`;

  let json;
  try {
    const res = await fetch(url);
    json = await res.json();
    if (!res.ok || json.error) {
      return fail('API error: ' + JSON.stringify(json.error || json));
    }
  } catch (e) {
    return fail('Network error: ' + e.message);
  }

  const items = Array.isArray(json.data) ? json.data : [];
  if (!items.length) return fail('No media returned.');

  const posts = items.map(function (m) {
    const caption = (m.caption || '').trim();
    const img = m.media_type === 'VIDEO' ? (m.thumbnail_url || m.media_url) : m.media_url;
    return {
      id: m.id,
      image: img,
      captionEn: caption.slice(0, 140),
      captionZh: '',                       // Graph API returns one caption only
      date: (m.timestamp || '').slice(0, 10),
      url: m.permalink || PROFILE
    };
  });

  const out = {
    _README: 'Auto-generated by scripts/fetch-instagram.js via GitHub Actions. Do not edit by hand.',
    generatedAt: new Date().toISOString(),
    profile: PROFILE,
    posts: posts
  };

  fs.writeFileSync(OUT, JSON.stringify(out, null, 2) + '\n');
  console.log('[instagram] wrote ' + posts.length + ' posts to data/instagram-feed.json');
}

main();
